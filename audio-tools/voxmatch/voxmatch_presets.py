def genre_values(name_or_index):
    """Полный набор значений жанрового пресета (ключ → значение)."""
    item = (GENRE_PRESETS[name_or_index] if isinstance(name_or_index, int)
            else next(g for g in GENRE_PRESETS if g[0] == name_or_index))
    _name, _desc, sections, extra = item
    vals = {}
    for sec, tname in sections.items():
        tpl = next(t for t in SECTION_TEMPLATES[sec] if t[0] == tname)
        vals.update(tpl[2])
    vals.update(extra)
    return vals
