def _t(timing=100, tmode=0, ttol=0, tsmooth=0, tflex=50, tlimit_on=False, tlimit=20, toffset=0,
       endings=False, ending=150):
    return dict(timing=timing, tmode=tmode, ttol=ttol, tsmooth=tsmooth, tflex=tflex,
                tlimit_on=tlimit_on, tlimit=tlimit, toffset=toffset, endings=endings, ending=ending)


def _p(pitch=100, smooth=30, vibrato=True, maxst=3, ptol=0, patt=0, prel=0, vib=100, detune=0,
       formant=0):
    return dict(pitch=pitch, smooth=smooth, vibrato=vibrato, maxst=maxst, ptol=ptol, patt=patt,
                prel=prel, vib=vib, detune=detune, formant=formant)


def _b(breath=True, breath_mode=0, breath_sens=50, breath_min=90, breath_pre=10, breath_post=10,
       tail=120, bxfade=10, breath_gain=100, breath_noclean=True):
    return dict(breath=breath, breath_mode=breath_mode, breath_sens=breath_sens,
                breath_min=breath_min, breath_pre=breath_pre, breath_post=breath_post, tail=tail,
                bxfade=bxfade, breath_gain=breath_gain, breath_noclean=breath_noclean)


def _c(clicks=True, deess=True, deess_db=5, level=True, level_str=70, gate=False, gate_db=50):
    return dict(clicks=clicks, deess=deess, deess_db=deess_db, level=level, level_str=level_str,
                gate=gate, gate_db=gate_db)


def _d(dyn=False, dyn_amount=100, dyn_speed=50):
    return dict(dyn=dyn, dyn_amount=dyn_amount, dyn_speed=dyn_speed)


