"""Write build/installer_i18n.iss: the installer's [Languages] and its own
texts ([CustomMessages]) taken from i18n/locales. Run before ISCC:
    python tools/gen_installer_i18n.py
Languages Inno Setup has no translation for (it ships the major ones) are
skipped at compile time, so the installer is English there — the app itself
is still translated."""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from i18n import LANGUAGES  # noqa: E402

# our code → (Inno language name, messages file inside Inno's Languages\)
INNO = {
    "en": ("english", None),
    "uk": ("ukrainian", "Ukrainian.isl"),
    "ru": ("russian", "Russian.isl"),
    "es": ("spanish", "Spanish.isl"),
    "pt-BR": ("brazilianportuguese", "BrazilianPortuguese.isl"),
    "de": ("german", "German.isl"),
    "fr": ("french", "French.isl"),
    "it": ("italian", "Italian.isl"),
    "pl": ("polish", "Polish.isl"),
    "tr": ("turkish", "Turkish.isl"),
    "nl": ("dutch", "Dutch.isl"),
    "zh-CN": ("chinesesimplified", "ChineseSimplified.isl"),
    "zh-TW": ("chinesetraditional", "ChineseTraditional.isl"),
    "ja": ("japanese", "Japanese.isl"),
    "ko": ("korean", "Korean.isl"),
    "id": ("indonesian", "Indonesian.isl"),
}
MESSAGES = {"Options": "installer.options", "AutostartTask": "installer.autostart"}


def main() -> None:
    assert set(INNO) == set(LANGUAGES), "keep INNO in step with i18n.LANGUAGES"
    languages, messages = ["[Languages]"], ["[CustomMessages]"]
    for code in LANGUAGES:
        name, isl = INNO[code]
        with open(os.path.join(ROOT, "i18n", "locales", f"{code}.json"), encoding="utf-8") as f:
            strings = json.load(f)
        lines = [f"{name}.{msg}={strings[key]}" for msg, key in MESSAGES.items()]
        if isl is None:
            languages.append(f'Name: "{name}"; MessagesFile: "compiler:Default.isl"')
            messages += lines
            continue
        guard = f'#if FileExists(CompilerPath + "Languages\\{isl}")'
        languages += [guard, f'Name: "{name}"; MessagesFile: "compiler:Languages\\{isl}"', "#endif"]
        messages += [guard, *lines, "#endif"]
    out = os.path.join(ROOT, "build", "installer_i18n.iss")
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, "w", encoding="utf-8-sig") as f:  # Inno needs the BOM for UTF-8
        f.write("; Generated by tools/gen_installer_i18n.py — do not edit.\n")
        f.write("\n".join(languages + [""] + messages) + "\n")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
